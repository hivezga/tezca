// The store
// ---------------------------------------------------------------------------

#[derive(Clone, Debug, Default, PartialEq)]
pub struct Entry {
    pub id: String,
    pub exec: String,
    pub label: String,
    pub enabled: bool,
    /// Seconds to wait before launching. Useful for anything that wants the bar
    /// and tray up first.
    pub delay: u32,
}

#[derive(Clone, Debug, Default, PartialEq)]
struct Store {
    entries: Vec<Entry>,
    /// Ids from [`SHIPPED`] the user has switched off.
    disabled: Vec<String>,
}

const HEADER: &str = "\
-- ~/.config/tezca/startup.lua — generated by `tezca startup`.
--
-- What launches at login, on top of (and alongside) the shipped services in
-- conf.d/autostart.lua. Read by that file through util.load, so a syntax error
-- here costs you these entries and nothing else — never the session.
--
-- DATA, not code: a bare `return { … }` table. `entries` are your own apps;
-- `disabled` lists shipped service ids you have turned off.
";

fn path() -> Result<PathBuf, String> {
    Ok(repo::config_home()?.join("tezca").join("startup.lua"))
}

/// Create the file if absent, so autostart.lua always finds something.
/// Called by `tezca link`.
pub fn seed() -> Result<bool, String> {
    let p = path()?;
    if p.exists() {
        return Ok(false);
    }
    atomic::write(&p, &render(&Store::default()))?;
    Ok(true)
}

fn read() -> Result<Store, String> {
    let text = std::fs::read_to_string(path()?).unwrap_or_default();
    Ok(parse(&text))
}

fn write(store: &Store) -> Result<(), String> {
    atomic::write(&path()?, &render(store))
}

/// Escape a value for a double-quoted Lua string.
fn lua_str(v: &str) -> String {
    format!("\"{}\"", v.replace('\\', "\\\\").replace('"', "\\\""))
}

fn unlua_str(lit: &str) -> String {
    let t = lit.trim().trim_end_matches(',').trim();
    match t.strip_prefix('"').and_then(|s| s.strip_suffix('"')) {
        Some(inner) => inner.replace("\\\"", "\"").replace("\\\\", "\\"),
        None => t.to_string(),
    }
}

fn render(store: &Store) -> String {
    let mut s = String::from(HEADER);
    s.push_str("\nreturn {\n    entries = {\n");
    for e in &store.entries {
        s.push_str(&format!(
            "        {{ id = {}, exec = {}, label = {}, enabled = {}, delay = {} }},\n",
            lua_str(&e.id),
            lua_str(&e.exec),
            lua_str(&e.label),
            e.enabled,
            e.delay
        ));
    }
    s.push_str("    },\n    disabled = {");
    if !store.disabled.is_empty() {
        s.push(' ');
        let ids: Vec<String> = store.disabled.iter().map(|d| lua_str(d)).collect();
        s.push_str(&ids.join(", "));
        s.push(' ');
    }
    s.push_str("},\n}\n");
    s
}

/// Line scanner over the grammar [`render`] emits — we are the only writer, so
/// the accepted grammar is exactly the produced one (same approach as the
/// override store).
fn parse(text: &str) -> Store {
    let mut store = Store::default();
    for raw in text.lines() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with("--") {
            continue;
        }
        if let Some(rest) = line.strip_prefix("disabled = {") {
            let inner = rest.trim_end_matches(',').trim().trim_end_matches('}');
            store.disabled = inner
                .split(',')
                .map(unlua_str)
                .filter(|s| !s.is_empty())
                .collect();
            continue;
        }
        if line.starts_with('{') && line.contains("exec") {
            if let Some(e) = parse_entry(line) {
                store.entries.push(e);
            }
        }
    }
    store
}

fn parse_entry(line: &str) -> Option<Entry> {
    let inner = line.trim().trim_start_matches('{').trim_end_matches(',').trim_end_matches('}');
    let mut e = Entry { enabled: true, ..Default::default() };
    // Split on commas that are not inside a quoted string — a label or command
    // may legitimately contain one ("Firefox, private window").
    for field in split_fields(inner) {
        let Some((k, v)) = field.split_once('=') else { continue };
        match k.trim() {
            "id" => e.id = unlua_str(v),
            "exec" => e.exec = unlua_str(v),
            "label" => e.label = unlua_str(v),
            "enabled" => e.enabled = v.trim().trim_end_matches(',').trim() != "false",
            "delay" => e.delay = unlua_str(v).parse().unwrap_or(0),
            _ => {}
        }
    }
    (!e.exec.is_empty()).then(|| {
        if e.id.is_empty() {
            e.id = slug(&e.exec);
        }
        if e.label.is_empty() {
            e.label = e.id.clone();
        }
        e
    })
}

/// Split `a = "x", b = 1` on top-level commas only.
fn split_fields(s: &str) -> Vec<String> {
    let mut out = vec![String::new()];
    let (mut in_str, mut escaped) = (false, false);
    for ch in s.chars() {
        if escaped {
            out.last_mut().expect("non-empty").push(ch);
            escaped = false;
            continue;
        }
        match ch {
            '\\' if in_str => {
                escaped = true;
                out.last_mut().expect("non-empty").push(ch);
            }
            '"' => {
                in_str = !in_str;
                out.last_mut().expect("non-empty").push(ch);
            }
            ',' if !in_str => out.push(String::new()),
            _ => out.last_mut().expect("non-empty").push(ch),
        }
    }
    out
}

/// A stable id derived from a command: `uwsm app -- discord.desktop` → `discord`.
///
/// The name is the *first* real word, not the last: `syncthing serve
/// --no-browser` is the syncthing entry, not the "serve" one. Launcher wrappers
/// and flags are skipped to get at it.
fn slug(exec: &str) -> String {
    const WRAPPERS: &[&str] = &["uwsm", "app", "--", "sh", "-c", "exec", "env", "systemd-run"];
    let word = exec
        .split_whitespace()
        .find(|w| !w.starts_with('-') && !WRAPPERS.contains(w))
        .unwrap_or("app");
    let base = word.rsplit('/').next().unwrap_or(word);
    let base = base.strip_suffix(".desktop").unwrap_or(base);
    let cleaned: String = base
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() || c == '-' || c == '_' { c } else { '-' })
        .collect();
    let cleaned = cleaned.trim_matches('-').to_lowercase();
    if cleaned.is_empty() { "app".to_string() } else { cleaned }
}

