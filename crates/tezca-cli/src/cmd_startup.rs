//! `tezca startup` — what launches when you log in.
//!
//!   list [--machine]                     shipped services + your own entries
//!   add <command> [--label L] [--delay N] [--id ID]
//!   remove <id>
//!   enable <id> | disable <id>           works for shipped services too
//!   run <id>                             launch it now, to test it
//!
//! ## Why a data file and not "just edit autostart.lua"
//!
//! `conf.d/autostart.lua` is a symlink into the repo checkout. Adding an app by
//! editing it dirties the working tree, publishes machine-local choices, and
//! breaks `git pull` in a downstream clone. So the shipped list stays in the
//! repo, and *your* list lives in `~/.config/tezca/startup.lua`, which
//! autostart.lua reads through `util.load`.
//!
//! Like every other generated file here it is **data, not code**: a bare
//! `return { … }` table that the config only ever indexes into. A Lua error in
//! the Hyprland config is not a warning — it drops the session into emergency
//! mode, one keybind on a black screen — and `util.load` degrades a broken file
//! to `nil` rather than letting that happen.

use crate::{atomic, repo, term, validate};
use std::path::PathBuf;
use std::process::{Command, Stdio};

/// The services `conf.d/autostart.lua` launches, in the order it launches them.
///
/// Kept in step with that file by hand — it is a short, rarely-changing list, and
/// the alternative (parsing Lua to discover them) is far worse. `essential`
/// entries cannot be disabled from here: without the bar there is no way back to
/// the Settings window that would re-enable it.
const SHIPPED: &[(&str, &str, bool, &str)] = &[
    // (id, label, essential, what turning it off costs you)
    ("polkit", "Polkit agent", false, "GUI password prompts (mounting, pkexec) stop appearing"),
    ("cliphist-text", "Clipboard history (text)", false, "SUPER+V has no text history"),
    ("cliphist-image", "Clipboard history (images)", false, "SUPER+V has no image history"),
    ("tezca-bar", "Tezca menubar", true, ""),
    ("swaync", "Notification centre", false, "no notifications at all"),
    ("elephant", "Launcher backend", false, "SUPER+SPACE opens but finds nothing"),
    ("walker", "Launcher service", false, "SUPER+SPACE cold-starts (~1.2s instead of ~90ms)"),
    ("awww", "Wallpaper daemon", false, "no wallpaper — a flat obsidian background"),
    ("hypridle", "Idle daemon", false, "no idle lock or screen blanking"),
    ("tezca-dock", "Tezca dock", false, "the magnifying dock does not appear"),
    ("wallpaper", "Apply wallpaper", false, "the wallpaper is not painted at login"),
];

pub fn run(args: &[&str]) -> i32 {
    let r = match args.first().copied() {
        None | Some("list") => cmd_list(args.get(1..).unwrap_or(&[])),
        Some("add") => cmd_add(&args[1..]),
        Some("remove") | Some("rm") => cmd_remove(&args[1..]),
        Some("enable") => cmd_set_enabled(&args[1..], true),
        Some("disable") => cmd_set_enabled(&args[1..], false),
        Some("run") => cmd_run(&args[1..]),
        Some("-h") | Some("--help") => {
            print_help();
            Ok(())
        }
        Some(other) => Err(format!(
            "unknown startup subcommand: {other}\n  try: list · add <command> · remove <id> · \
             enable <id> · disable <id> · run <id>"
        )),
    };
    match r {
        Ok(()) => 0,
        Err(e) => {
            eprintln!("{} {e}", term::red("error:"));
            1
        }
    }
}

