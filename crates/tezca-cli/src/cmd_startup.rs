fn cmd_list(args: &[&str]) -> Result<(), String> {
    let store = read()?;
    let machine = args.iter().any(|a| *a == "--machine" || *a == "-m");

    if machine {
        for (id, label, essential, cost) in SHIPPED {
            println!("@service");
            println!("id={id}");
            println!("label={label}");
            println!("enabled={}", !store.disabled.iter().any(|d| d == id));
            println!("essential={essential}");
            println!("cost={cost}");
        }
        for e in &store.entries {
            println!("@entry");
            println!("id={}", e.id);
            println!("label={}", e.label);
            println!("exec={}", e.exec);
            println!("enabled={}", e.enabled);
            println!("delay={}", e.delay);
        }
        return Ok(());
    }

    println!("{}", term::header("tezca startup"));
    println!();
    println!("  {}", term::bold("Tezca services"));
    for (id, label, essential, _) in SHIPPED {
        let on = !store.disabled.iter().any(|d| d == id);
        let dot = if on { term::green("●") } else { term::dim("○") };
        let tag = if *essential { term::dim("  (essential)") } else { String::new() };
        println!("  {dot} {:<26} {}{tag}", term::bold(label), term::dim(id));
    }
    println!();
    println!("  {}", term::bold("Your apps"));
    if store.entries.is_empty() {
        println!("  {}", term::dim("none — `tezca startup add \"<command>\"`"));
    }
    for e in &store.entries {
        let dot = if e.enabled { term::green("●") } else { term::dim("○") };
        let delay = if e.delay > 0 { format!("  +{}s", e.delay) } else { String::new() };
        println!("  {dot} {:<26} {}", term::bold(&e.label), term::dim(&format!("{}{delay}", e.exec)));
    }
    println!();
    Ok(())
}

fn cmd_add(args: &[&str]) -> Result<(), String> {
    let mut exec = String::new();
    let mut label = String::new();
    let mut id = String::new();
    let mut delay: u32 = 0;

    let mut it = args.iter().copied();
    while let Some(a) = it.next() {
        match a {
            "--label" => label = it.next().ok_or("--label needs a value")?.to_string(),
            "--id" => id = it.next().ok_or("--id needs a value")?.to_string(),
            "--delay" => {
                delay = it
                    .next()
                    .and_then(|v| v.parse().ok())
                    .ok_or("--delay needs a whole number of seconds")?
            }
            // `--desktop foo.desktop` is what the GUI sends: uwsm resolves a
            // desktop id itself, so nothing here has to parse .desktop files.
            "--desktop" => {
                let app = it.next().ok_or("--desktop needs an application id")?;
                exec = format!("uwsm app -- {app}");
            }
            other if other.starts_with('-') => return Err(format!("unknown flag: {other}")),
            other => exec = other.to_string(),
        }
    }
    if exec.trim().is_empty() {
        return Err("usage: tezca startup add \"<command>\" [--label L] [--delay N]".into());
    }
    validate::exec_line(&exec)?;
    if !label.is_empty() {
        validate::exec_line(&label)?;
    }

    let mut store = read()?;
    let id = if id.is_empty() { slug(&exec) } else { id };
    validate::startup_id(&id)?;
    // Ids must be unique — they address an entry for enable/disable/remove.
    let id = unique_id(&store, &id);
    let label = if label.is_empty() { title_case(&id) } else { label };
    store.entries.push(Entry { id: id.clone(), exec, label: label.clone(), enabled: true, delay });
    write(&store)?;
    println!("  {} added {} ({id})", term::green("✓"), term::bold(&label));
    println!("  {}", term::dim("starts at your next login — `tezca startup run <id>` to test it now"));
    Ok(())
}

fn unique_id(store: &Store, base: &str) -> String {
    if !store.entries.iter().any(|e| e.id == base) {
        return base.to_string();
    }
    (2..).map(|n| format!("{base}-{n}")).find(|c| !store.entries.iter().any(|e| e.id == *c)).unwrap_or_default()
}

fn title_case(s: &str) -> String {
    let s = s.replace(['-', '_'], " ");
    let mut c = s.chars();
    match c.next() {
        Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
        None => s.clone(),
    }
}

fn cmd_remove(args: &[&str]) -> Result<(), String> {
    let id = args.first().copied().ok_or("usage: tezca startup remove <id>")?;
    let mut store = read()?;
    let before = store.entries.len();
    store.entries.retain(|e| e.id != id);
    if store.entries.len() == before {
        return Err(format!("no startup entry with id '{id}' (see `tezca startup list`)"));
    }
    write(&store)?;
    println!("  {} removed {id}", term::green("✓"));
    Ok(())
}

fn cmd_set_enabled(args: &[&str], on: bool) -> Result<(), String> {
    let id = args
        .first()
        .copied()
        .ok_or_else(|| format!("usage: tezca startup {} <id>", if on { "enable" } else { "disable" }))?;
    let mut store = read()?;

    if let Some(e) = store.entries.iter_mut().find(|e| e.id == id) {
        e.enabled = on;
        let label = e.label.clone();
        write(&store)?;
        println!("  {} {label} {}", term::green("✓"), if on { "enabled" } else { "disabled" });
        return Ok(());
    }

    let Some((_, label, essential, cost)) = SHIPPED.iter().find(|(sid, _, _, _)| *sid == id) else {
        return Err(format!("no startup entry with id '{id}' (see `tezca startup list`)"));
    };
    if *essential && !on {
        return Err(format!(
            "'{id}' is essential and cannot be disabled — without it there is no way back \
             to the settings window that would switch it on again"
        ));
    }
    if on {
        store.disabled.retain(|d| d != id);
    } else if !store.disabled.iter().any(|d| d == id) {
        store.disabled.push(id.to_string());
    }
    write(&store)?;
    println!("  {} {label} {}", term::green("✓"), if on { "enabled" } else { "disabled" });
    if !on && !cost.is_empty() {
        println!("  {} {}", term::yellow("!"), term::dim(cost));
    }
    println!("  {}", term::dim("takes effect at your next login"));
    Ok(())
}

fn cmd_run(args: &[&str]) -> Result<(), String> {
    let id = args.first().copied().ok_or("usage: tezca startup run <id>")?;
    let store = read()?;
    let e = store
        .entries
        .iter()
        .find(|e| e.id == id)
        .ok_or_else(|| format!("no startup entry with id '{id}'"))?;
    // Through a shell, exactly as autostart.lua launches it, so testing an entry
    // exercises the same command line it will get at login.
    Command::new("sh")
        .arg("-c")
        .arg(&e.exec)
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .spawn()
        .map_err(|err| format!("could not launch: {err}"))?;
    println!("  {} launched {}", term::green("✓"), term::bold(&e.label));
    Ok(())
}

fn print_help() {
    println!("{}", term::header("tezca startup"));
    println!();
    for (c, d) in [
        ("list", "shipped services + your own entries"),
        ("add \"<cmd>\"", "add an app (--label, --delay N, --desktop id)"),
        ("remove <id>", "delete one of your entries"),
        ("enable <id>", "switch an entry or shipped service back on"),
        ("disable <id>", "switch one off (shipped services included)"),
        ("run <id>", "launch it now, without logging out"),
    ] {
        println!("  {:<18} {}", term::cyan(c), term::dim(d));
    }
    println!();
    println!("{}", term::dim("  Your list lives in ~/.config/tezca/startup.lua, outside the repo."));
}

#[cfg(test)]
mod tests {
    use super::*;

    fn entry(id: &str, exec: &str) -> Entry {
        Entry {
            id: id.into(),
            exec: exec.into(),
            label: title_case(id),
            enabled: true,
            delay: 0,
        }
    }

    #[test]
    fn round_trips_entries_and_disabled_services() {
        let store = Store {
            entries: vec![
                entry("discord", "uwsm app -- discord.desktop"),
                Entry { delay: 5, enabled: false, ..entry("syncthing", "syncthing serve") },
            ],
            disabled: vec!["tezca-dock".into(), "hypridle".into()],
        };
        let text = render(&store);
        assert_eq!(parse(&text), store);
        // Rewriting is a fixed point — the file must not grow on repeated writes.
        assert_eq!(render(&parse(&text)), text);
    }

    #[test]
    fn a_command_containing_a_comma_or_a_quote_survives_the_round_trip() {
        // Both would have broken a naive `split(',')` / unquoted render — and the
        // failure mode is a *config file*, so it has to be right.
        let store = Store {
            entries: vec![entry("brave", r#"sh -c 'brave --args="a,b"'"#)],
            disabled: vec![],
        };
        let text = render(&store);
        assert_eq!(parse(&text), store);
        assert!(!text.contains("\n\n\n"));
    }

    #[test]
    fn an_empty_store_renders_a_table_that_is_still_valid_lua() {
        let text = render(&Store::default());
        assert!(text.contains("return {"));
        assert!(text.contains("entries = {"));
        assert!(text.contains("disabled = {},"));
        assert_eq!(parse(&text), Store::default());
    }

    #[test]
    fn derives_a_readable_id_from_a_command() {
        assert_eq!(slug("uwsm app -- discord.desktop"), "discord");
        assert_eq!(slug("syncthing serve --no-browser"), "syncthing");
        assert_eq!(slug("/usr/bin/nextcloud"), "nextcloud");
        assert_eq!(slug("uwsm app -- org.telegram.desktop.desktop"), "org-telegram-desktop");
        assert_eq!(slug(""), "app");
    }

    #[test]
    fn ids_stay_unique_so_enable_disable_addresses_one_entry() {
        let store = Store { entries: vec![entry("discord", "discord")], disabled: vec![] };
        assert_eq!(unique_id(&store, "discord"), "discord-2");
        assert_eq!(unique_id(&store, "slack"), "slack");
    }

    #[test]
    fn a_file_written_by_hand_without_optional_fields_still_loads() {
        let text = "return {\n  entries = {\n    { exec = \"foo --bar\" },\n  },\n}\n";
        let store = parse(text);
        assert_eq!(store.entries.len(), 1);
        assert_eq!(store.entries[0].exec, "foo --bar");
        assert_eq!(store.entries[0].id, "foo");
        assert!(store.entries[0].enabled, "an entry with no `enabled` key is on");
    }
}
